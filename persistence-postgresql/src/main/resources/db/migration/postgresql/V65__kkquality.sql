CREATE TABLE kkq_project (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id CHAR(36) NOT NULL,
  project_key VARCHAR(400) NOT NULL,
  name VARCHAR(255) NOT NULL,
  organization VARCHAR(255) NULL,
  visibility VARCHAR(32) NOT NULL DEFAULT 'private',
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkq_project_external_id UNIQUE (external_id),
  CONSTRAINT uk_kkq_project_key UNIQUE (project_key)
);

CREATE TABLE kkq_branch (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  name VARCHAR(255) NOT NULL,
  is_main BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkq_branch_project_name UNIQUE (project_id, name),
  CONSTRAINT fk_kkq_branch_project
    FOREIGN KEY (project_id) REFERENCES kkq_project(id) ON DELETE CASCADE
);

CREATE TABLE kkq_rule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  engine VARCHAR(64) NOT NULL,
  rule_key VARCHAR(255) NOT NULL,
  name VARCHAR(512) NOT NULL,
  severity VARCHAR(32) NULL,
  language VARCHAR(64) NULL,
  description TEXT NULL,
  remediation TEXT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkq_rule_engine_key UNIQUE (engine, rule_key)
);

CREATE TABLE kkq_analysis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  branch_id BIGINT NULL,
  analysis_id CHAR(36) NOT NULL,
  status VARCHAR(32) NOT NULL,
  revision VARCHAR(255) NULL,
  sarif_sha256 CHAR(64) NULL,
  issue_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at TIMESTAMPTZ(3) NULL,
  completed_at TIMESTAMPTZ(3) NULL,
  error TEXT NULL,
  CONSTRAINT uk_kkq_analysis_external_id UNIQUE (analysis_id),
  CONSTRAINT fk_kkq_analysis_project
    FOREIGN KEY (project_id) REFERENCES kkq_project(id) ON DELETE CASCADE,
  CONSTRAINT fk_kkq_analysis_branch
    FOREIGN KEY (branch_id) REFERENCES kkq_branch(id) ON DELETE SET NULL
);
CREATE INDEX idx_kkq_analysis_project ON kkq_analysis(project_id, created_at);
CREATE INDEX idx_kkq_analysis_status ON kkq_analysis(status, created_at);

CREATE TABLE kkq_issue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  branch_id BIGINT NULL,
  issue_key VARCHAR(64) NOT NULL,
  file_path VARCHAR(1024) NOT NULL,
  line INT NULL,
  engine VARCHAR(64) NULL,
  rule_key VARCHAR(255) NULL,
  severity VARCHAR(32) NULL,
  issue_type VARCHAR(32) NULL,
  message TEXT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
  assignee VARCHAR(255) NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkq_issue_key UNIQUE (issue_key),
  CONSTRAINT fk_kkq_issue_analysis
    FOREIGN KEY (analysis_id) REFERENCES kkq_analysis(id) ON DELETE CASCADE,
  CONSTRAINT fk_kkq_issue_project
    FOREIGN KEY (project_id) REFERENCES kkq_project(id) ON DELETE CASCADE
);
CREATE INDEX idx_kkq_issue_analysis ON kkq_issue(analysis_id);
CREATE INDEX idx_kkq_issue_project ON kkq_issue(project_id, status);
CREATE INDEX idx_kkq_issue_rule ON kkq_issue(engine, rule_key);

CREATE TABLE kkq_quality_gate (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NULL,
  external_id CHAR(36) NOT NULL,
  name VARCHAR(255) NOT NULL,
  conditions_json JSONB NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_kkq_quality_gate_external_id UNIQUE (external_id),
  CONSTRAINT uk_kkq_quality_gate_project_name UNIQUE (project_id, name),
  CONSTRAINT fk_kkq_quality_gate_project
    FOREIGN KEY (project_id) REFERENCES kkq_project(id) ON DELETE CASCADE
);

CREATE TABLE kkq_measure (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_id BIGINT NOT NULL,
  metric_key VARCHAR(128) NOT NULL,
  value_num DECIMAL(24,4) NULL,
  value_text TEXT NULL,
  CONSTRAINT uk_kkq_measure_analysis_metric UNIQUE (analysis_id, metric_key),
  CONSTRAINT fk_kkq_measure_analysis
    FOREIGN KEY (analysis_id) REFERENCES kkq_analysis(id) ON DELETE CASCADE
);
